#!/usr/bin/env python3
"""Fetch and build the licensed speech fixtures used to qualify the Whisper speech-to-text service.

Run as `python3 -I tools/speech/fixtures/fetch.py [--out DIR] [--strict]`. Standard library only, plus
ffmpeg/ffprobe on PATH. LibriSpeech comes from a parquet file, which needs pyarrow: it is read by
extract_parquet.py through `uv run --with pyarrow` unless pyarrow is already importable (set UV to
override the uv binary).

Every download is pinned: Hugging Face URLs name an exact commit and the sha256 of the bytes is checked
before anything is used. Downloaded files are untrusted data: each lives in its own new directory under
<out>/_downloads, nothing from them is executed, and archives are only parsed in memory (member names are
looked up, never used as paths). Output goes to <out> (default ~/.cache/localrouter-speech/fixtures):
the fixture files, refs.json (name -> text/language/source/license/duration_s) and manifest.json (which
is also written next to this script). Downloads are skipped when already present with the right sha256.
"""
