# Not part of the spec'd command: make ffmpeg output independent of its version string and timestamps.
REPRO = ["-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact"]


def log(msg):
    print(msg, file=sys.stderr, flush=True)


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url, dest, sha, byte_count=None):
    """Download url (first byte_count bytes if set) to dest, verifying the pinned sha256."""
    if dest.exists() and sha256_file(dest) == sha:
        return
    headers = {"User-Agent": "localrouter-speech-fixtures/1"}
    if byte_count:
        headers["Range"] = f"bytes=0-{byte_count - 1}"
    last = None
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers=headers)
            with urllib.request.urlopen(req, timeout=120) as resp:
                if byte_count and resp.status != 206:
                    raise RuntimeError(f"expected 206 for a range request, got {resp.status}")
                data = resp.read()
            if byte_count and len(data) != byte_count:
                raise RuntimeError(f"expected {byte_count} bytes, got {len(data)}")
            got = sha256_bytes(data)
            if got != sha:
                raise RuntimeError(f"sha256 mismatch for {url}: expected {sha}, got {got}")
            tmp = dest.with_name(dest.name + ".part")
            tmp.write_bytes(data)
            tmp.replace(dest)
            return
        except RuntimeError:
            raise
        except Exception as exc:  # network errors only; pin mismatches are not retried
            last = exc
            time.sleep(2 * (attempt + 1))
    raise RuntimeError(f"download failed for {url}: {last}")


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, stdin=subprocess.DEVNULL, **kw)


def ffmpeg(*args):
    run(["ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", *args])


def to_wav(src, dst):
    ffmpeg("-i", str(src), "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", *REPRO, "-y", str(dst))


def wav_samples(path):
    with wave.open(str(path), "rb") as w:
        assert w.getsampwidth() == 2 and w.getnchannels() == 1
        raw = w.readframes(w.getnframes())
        rate = w.getframerate()
    s = array("h")
    s.frombytes(raw)
    if sys.byteorder == "big":
        s.byteswap()
    return s, rate


def duration_s(path):
    with wave.open(str(path), "rb") as w:
        return round(w.getnframes() / w.getframerate(), 3)


def rms(samples):
    return math.sqrt(math.fsum(float(x) * x for x in samples) / len(samples))


def fresh_dir(path):
    path.mkdir(parents=True)
    return path


def png_bytes(size=16):
    def chunk(tag, body):
        return struct.pack(">I", len(body)) + tag + body + struct.pack(">I", zlib.crc32(tag + body))

    rows = b"".join(b"\x00" + bytes(v for x in range(size) for v in (x * 16, y * 16, 128)) for y in range(size))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def wav_data_offset(blob):
    """Offset of the first byte of the 'data' chunk payload in a RIFF/WAVE blob."""
    pos = 12
    while pos + 8 <= len(blob):
        tag, size = blob[pos:pos + 4], struct.unpack("<I", blob[pos + 4:pos + 8])[0]
        if tag == b"data":
            return pos + 8
        pos += 8 + size + (size & 1)
    raise ValueError("no data chunk")


def fleurs_members(prefix_bytes):
    """Yield (member name, bytes) for complete members in a truncated .tar.gz prefix, parsed in memory."""
    raw = zlib.decompressobj(31).decompress(prefix_bytes)
    tf = tarfile.open(fileobj=io.BytesIO(raw))
    try:
        for m in tf:
            if not m.isfile():
                continue
            data = tf.extractfile(m).read()
            if len(data) == m.size:
                yield m.name, data
    except tarfile.ReadError:
        return  # the cut-off final member


def read_tsv(path):
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        cols = line.split("\t")
        rows[cols[1]] = {"id": cols[0], "raw": cols[2], "normalized": cols[3], "gender": cols[6] if len(cols) > 6 else ""}
    return rows


def librispeech_rows(texts):
    return {t["id"]: t for t in texts}


def pyarrow_runner():
    probe = subprocess.run([sys.executable, "-I", "-c", "import pyarrow"], capture_output=True)
    if probe.returncode == 0:
        return [sys.executable, "-I"]
    uv = os.environ.get("UV") or shutil.which("uv") or str(Path.home() / ".local/opt/uv-0.12.24/uv")
    return [uv, "run", "--no-project", "--with", "pyarrow", "python", "-I"]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--strict", action="store_true", help="exit 2 if a produced file differs from the recorded manifest sha256")
    args = ap.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    dl_root, work = out / "_downloads", out / "_work"
    dl_root.mkdir(exist_ok=True)
    if work.exists():
        shutil.rmtree(work)
    work.mkdir()
    old_manifest = None
    if (HERE / "manifest.json").exists():
        old_manifest = json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))

    sources, refs, fixtures = {}, {}, {}

    def add_source(key, url, sha, nbytes, **extra):
        sources[key] = {"url": url, "sha256": sha, "bytes": nbytes, **extra}

    def add_fixture(name, filename, ref, source_keys, recipe):
        path = out / filename
        fixtures[name] = {"file": filename, "sha256": sha256_file(path), "size_bytes": path.stat().st_size,
                          "sources": source_keys, "recipe": recipe}
        refs[name] = ref

    # LibriSpeech (dev-clean utterances, from the HF parquet copy)
    ls_dir = dl_root / "librispeech_parquet"
    if not ls_dir.exists():
        fresh_dir(ls_dir)
    ls_parquet = ls_dir / "validation-00000-of-00001.parquet"
    log("librispeech parquet")
    download(LS_URL, ls_parquet, LS_SHA)
    add_source("librispeech_parquet", LS_URL, LS_SHA, ls_parquet.stat().st_size, commit=LS_COMMIT, license=LS_LICENSE)
    ls_flac = dl_root / "librispeech_extracted"
    if ls_flac.exists():
        shutil.rmtree(ls_flac)
    fresh_dir(ls_flac)
    helper = HERE / "extract_parquet.py"
    run([*pyarrow_runner(), str(helper), str(ls_parquet), str(ls_flac)], cwd=str(out))
    texts = json.loads((ls_flac / "texts.json").read_text(encoding="utf-8"))
    by_id = librispeech_rows(texts)
    wavs = fresh_dir(work / "utt")
    for t in texts:
        to_wav(ls_flac / f"{t['id']}.flac", wavs / f"{t['id']}.wav")
    ls_src = ["librispeech_parquet"]
    ls_license_note = "CC-BY-4.0 (LibriSpeech, Panayotov et al. 2015; audio from public-domain LibriVox)"

    def ls_ref(ids, wav):
        return {"text": " ".join(by_id[i]["text"] for i in ids), "language": "en",
                "source": f"{LS_URL}#{'+'.join(ids)}", "license": ls_license_note, "duration_s": duration_s(wav)}

    # 1. single English utterances
    for uid in SINGLE_UTTERANCES:
        name = f"en_librispeech_{uid}"
        shutil.copyfile(wavs / f"{uid}.wav", out / f"{name}.wav")
        add_fixture(name, f"{name}.wav", ls_ref([uid], out / f"{name}.wav"), ls_src, f"ffmpeg convert {uid}.flac")

    # 3. long-form: consecutive utterances joined with the concat demuxer
    def long_form(name, prefix, target):
        ids, total = [], 0.0
        for t in texts:
            if not t["id"].startswith(prefix):
                continue
            ids.append(t["id"])
            total += duration_s(wavs / f"{t['id']}.wav")
            if total >= target:
                break
        assert total >= target, (name, total)
        lst = work / f"{name}.txt"
        lst.write_text("".join(f"file '{wavs / (i + '.wav')}'\n" for i in ids), encoding="utf-8")
        dst = out / f"{name}.wav"
        ffmpeg("-f", "concat", "-safe", "0", "-i", str(lst), "-c", "copy", *REPRO, "-y", str(dst))
        ref = ls_ref(ids, dst)
        ref["utterances"] = ids
        add_fixture(name, f"{name}.wav", ref, ls_src, f"ffmpeg concat of {len(ids)} utterances (speaker 1272), reference = texts joined with spaces")

    long_form("long_en_librispeech_60s", *LONG_60S)
    long_form("long_en_librispeech_270s", *LONG_270S)

    # 2. multilingual FLEURS (leading bytes of each test shard only)
    for lang_dir, (iso, pre, tar_sha, tsv_sha) in FLEURS.items():
        base = f"https://huggingface.co/datasets/google/fleurs/resolve/{FLEURS_COMMIT}/data/{lang_dir}"
        d = dl_root / f"fleurs_{lang_dir}"
        if not d.exists():
            fresh_dir(d)
        tar_prefix, tsv = d / "test.tar.gz.prefix", d / "test.tsv"
        log(f"fleurs {lang_dir}")
        download(f"{base}/audio/test.tar.gz", tar_prefix, tar_sha, FLEURS_PREFIX)
        download(f"{base}/test.tsv", tsv, tsv_sha)
        add_source(f"fleurs_{lang_dir}_tar", f"{base}/audio/test.tar.gz", tar_sha, FLEURS_PREFIX, range=f"bytes=0-{FLEURS_PREFIX - 1}", commit=FLEURS_COMMIT, license=FLEURS_LICENSE)
        add_source(f"fleurs_{lang_dir}_tsv", f"{base}/test.tsv", tsv_sha, tsv.stat().st_size, commit=FLEURS_COMMIT, license=FLEURS_LICENSE)
        meta = read_tsv(tsv)
        taken = 0
        for member, data in fleurs_members(tar_prefix.read_bytes()):
            fname = member.rsplit("/", 1)[-1]
            if fname not in meta:
                continue
            taken += 1
            name = f"{pre}_fleurs_{taken:02d}"
            raw = fresh_dir(work / f"raw_{name}") / "in.wav"
            raw.write_bytes(data)
            to_wav(raw, out / f"{name}.wav")
            m = meta[fname]
            ref = {"text": m["raw"], "language": iso, "source": f"{base}/audio/test.tar.gz#{member}",
                   "license": "CC-BY-4.0 (FLEURS, Conneau et al. 2022)", "duration_s": duration_s(out / f"{name}.wav"),
                   "text_normalized": m["normalized"], "fleurs_id": m["id"], "speaker_gender": m["gender"]}
            add_fixture(name, f"{name}.wav", ref, [f"fleurs_{lang_dir}_tar", f"fleurs_{lang_dir}_tsv"], f"member {member} of the tar.gz prefix, ffmpeg convert")
            if taken == FLEURS_PER_LANG:
                break
        assert taken == FLEURS_PER_LANG, f"only {taken} complete {lang_dir} utterances in the prefix"

    # 4. silence, noise, speech-in-noise
    gen_src = "generated by fetch.py with ffmpeg"
    silence = out / "silence_10s.wav"
    ffmpeg("-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono", "-t", "10", "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", *REPRO, "-y", str(silence))
    add_fixture("silence_10s", silence.name, {"text": "", "language": None, "source": gen_src, "license": GENERATED_LICENSE, "duration_s": duration_s(silence),
                                              "expect": "empty or near-empty transcript"}, [], "ffmpeg lavfi anullsrc, 10 s")
    noise = out / "noise_10s.wav"
    ffmpeg("-f", "lavfi", "-i", "anoisesrc=color=white:amplitude=0.1:seed=42:sample_rate=16000:duration=10", "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", *REPRO, "-y", str(noise))
    nsamples, _ = wav_samples(noise)
    add_fixture("noise_10s", noise.name, {"text": "", "language": None, "source": gen_src, "license": GENERATED_LICENSE, "duration_s": duration_s(noise),
                                          "expect": "empty or near-empty transcript", "rms_dbfs": round(20 * math.log10(rms(nsamples) / 32768), 1)},
                [], "ffmpeg lavfi anoisesrc white, amplitude 0.1, seed 42, 10 s")
    base_wav = out / f"en_librispeech_{BASE_UTTERANCE}.wav"
    speech, _ = wav_samples(base_wav)
    pink = work / "pink.wav"
    ffmpeg("-f", "lavfi", "-i", f"anoisesrc=color=pink:amplitude=0.5:seed=7:sample_rate=16000:duration={math.ceil(duration_s(base_wav)) + 1}",
           "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", "-y", str(pink))
    pink_samples, _ = wav_samples(pink)
    gain = rms(speech) / (rms(pink_samples) * 10 ** (SNR_DB / 20))
    mixed = out / "speech_in_pink_noise_10db.wav"
    ffmpeg("-i", str(base_wav), "-i", str(pink), "-filter_complex",
           f"[1:a]volume={gain:.9f}[n];[0:a][n]amix=inputs=2:duration=first:normalize=0", "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", *REPRO, "-y", str(mixed))
    mix_samples, _ = wav_samples(mixed)
    assert len(mix_samples) == len(speech) and max(abs(x) for x in mix_samples) < 32767, "mix clipped or length changed"
    snr = 20 * math.log10(rms(speech) / rms(array("d", (m - s for m, s in zip(mix_samples, speech)))))
    ref = ls_ref([BASE_UTTERANCE], mixed)
    ref.update({"source": f"{LS_URL}#{BASE_UTTERANCE} (mixed with generated pink noise)", "snr_db_target": SNR_DB, "snr_db_measured": round(snr, 2)})
    add_fixture("speech_in_pink_noise_10db", mixed.name, ref, ls_src, f"{BASE_UTTERANCE} + ffmpeg anoisesrc pink seed 7 scaled to {SNR_DB} dB SNR (rms based), amix normalize=0")

    # 6. non-16 kHz encodings of the same utterance, kept in their native format (not converted)
    base_ref = refs[f"en_librispeech_{BASE_UTTERANCE}"]
    src_flac = ls_flac / f"{BASE_UTTERANCE}.flac"
    variants = [
        ("en_44k1_stereo.mp3", ["-ar", "44100", "-ac", "2", "-c:a", "libmp3lame", "-b:a", "128k"], "44.1 kHz stereo MP3 128k (libmp3lame)", 44100, 2),
        ("en_48k_stereo_opus.ogg", ["-ar", "48000", "-ac", "2", "-c:a", "libopus", "-b:a", "64k"], "48 kHz stereo Opus in Ogg, 64k (libopus)", 48000, 2),
        ("en_44k1_stereo.flac", ["-ar", "44100", "-ac", "2", "-c:a", "flac"], "44.1 kHz stereo FLAC", 44100, 2),
    ]
    for filename, codec_args, desc, rate, ch in variants:
        ffmpeg("-i", str(src_flac), *codec_args, *REPRO, "-y", str(out / filename))
        ref = {k: base_ref[k] for k in ("text", "language", "source", "license", "duration_s")}
        ref.update({"format": desc, "sample_rate": rate, "channels": ch, "derived_from": f"en_librispeech_{BASE_UTTERANCE}"})
        add_fixture(Path(filename).stem + "_" + Path(filename).suffix[1:], filename, ref, ls_src, f"ffmpeg re-encode of {BASE_UTTERANCE}.flac: {desc}")

    # 5. malformed inputs (rejection tests)
    blob = base_wav.read_bytes()
    data_start = wav_data_offset(blob)
    malformed = {
        "malformed_truncated_wav": ("malformed_truncated.wav", blob[:data_start + (len(blob) - data_start) // 2], "valid WAV cut to half its data; the header still claims the full length"),
        "malformed_random_wav": ("malformed_random.wav", random.Random(20260101).randbytes(8192), "8192 random bytes (random.Random(20260101).randbytes) named .wav"),
        "malformed_empty_wav": ("malformed_empty.wav", b"", "zero-byte file named .wav"),
        "malformed_notaudio_png": ("malformed_notaudio.png", png_bytes(), "valid 16x16 PNG, not audio"),
    }
    for name, (filename, content, recipe) in malformed.items():
        (out / filename).write_bytes(content)
        add_fixture(name, filename, {"malformed": True, "source": gen_src, "license": GENERATED_LICENSE, "note": recipe}, [], recipe)

    # outputs
    ffprobe = run(["ffmpeg", "-version"], capture_output=True, text=True).stdout.splitlines()[0]
    manifest = {"schema": 1, "ffmpeg": ffprobe,
                "note": "fixture sha256 values depend on the ffmpeg build (resampler/encoders); source sha256 values are the pins fetch.py enforces",
                "sources": sources, "fixtures": fixtures}
    mism = []
    if old_manifest:
        for n, f in fixtures.items():
            o = old_manifest.get("fixtures", {}).get(n)
            if o and o["sha256"] != f["sha256"]:
                mism.append(n)
    text = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    (HERE / "manifest.json").write_text(text, encoding="utf-8")
    (out / "manifest.json").write_text(text, encoding="utf-8")
    (out / "refs.json").write_text(json.dumps(refs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    shutil.rmtree(work)
    total = sum(p.stat().st_size for p in out.iterdir() if p.is_file())
    log(f"wrote {len(fixtures)} fixtures to {out} ({total} bytes)")
    if mism:
        log("fixture sha256 differs from the previous manifest (different ffmpeg build?): " + ", ".join(mism))
        if args.strict:
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
