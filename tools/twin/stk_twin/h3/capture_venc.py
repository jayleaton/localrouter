"""python -m stk_twin.h3.capture_venc --out DIR [--size 768x448 --seed 7 --tiles 1:1 --models DIR].
Encoder-only capture of a fixed canvas generated by the portable noise stream; no image decode dependency.
The full latent hash covers unrecorded tiles. This is not an end-to-end image-to-video capture.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import numpy as np
import torch
from ..qwen_image import noise
from ..rec import REC
from . import vae_video as V
from .vae_video_enc import VideoEncoder

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--models", default=os.environ.get("VMODELS", ""))
    ap.add_argument("--checkpoint", default=os.environ.get("VVAE", ""))
    ap.add_argument("--size", default="768x448")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--tiles", default="1:1")
    a = ap.parse_args()
    W, H = [int(x) for x in a.size.lower().split("x")]
    if min(H, W)<32 or H%16 or W%16:
        raise SystemExit("--size: sides must be >=32 and multiples of 16")
    tiles = {tuple(int(x) for x in t.split(":")) for t in a.tiles.split(",") if t}
    grid = (len(V.split_tiles(H)[0]), len(V.split_tiles(W)[0]))
    if not tiles or any(len(t)!=2 or not (0<=t[0]<grid[0] and 0<=t[1]<grid[1]) for t in tiles):
        raise SystemExit(f"--tiles: select row:col within {grid}")
    out = Path(a.out)
    if (out/"ops.jsonl").exists():
        raise SystemExit("--out already contains a capture")
    ck = a.checkpoint or str(Path(a.models)/"vae/minimax_h3_video_vae_fp16.safetensors")
    encoder = VideoEncoder.from_checkpoint(ck)
    pixels = np.clip(noise(a.seed, H*W*3)*np.float32(0.2)+np.float32(0.5), 0, 1)
    rgb = torch.from_numpy(pixels.reshape(H, W, 3)).to("cuda").contiguous()
    REC.start(out)
    try:
        with torch.inference_mode():
            z = encoder.encode(rgb, rec=lambda r, c: r<0 or (r, c) in tiles)
        sha = hashlib.sha256(z.cpu().numpy().tobytes()).hexdigest()
        REC.note("venc_shapes", width=W, height=H, seed=a.seed, latent=list(z.shape), tiles=sorted(tiles),
                 grid=list(grid), sha256=sha, rgb_sha256=hashlib.sha256(pixels.tobytes()).hexdigest())
    finally:
        REC.stop()
    print(json.dumps({"venc_capture": str(out), "ops": REC.n, "sha256": sha, "latent": list(z.shape)}))

if __name__ == "__main__":
    main()
